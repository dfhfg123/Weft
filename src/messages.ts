export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    vars[key] === undefined ? match : String(vars[key]),
  );
}

export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const table = locale === 'zh' ? zh : en;
  return interpolate(table[key] ?? en[key], vars);
}

export function formatLongDate(locale: Locale, date = new Date()): string {
  return date.toLocaleDateString(locale === 'zh' ? 'zh-CN' : 'en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });
}

export function countUnit(
  locale: Locale,
  kind: 'note' | 'thread',
  count: number,
): string {
  return translate(
    locale,
    kind === 'note'
      ? count === 1
        ? 'unit.noteOne'
        : 'unit.noteMany'
      : count === 1
        ? 'unit.threadOne'
        : 'unit.threadMany',
  );
}
